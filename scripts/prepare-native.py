#!/usr/bin/env python3
"""Build the original C with explicitly bounded portability/safety changes.
Never edits calculator sources. All replacements are asserted to detect upstream drift.
"""
from pathlib import Path
import re
ROOT=Path(__file__).resolve().parent.parent
OUT=ROOT/'android/native/generated'
OUT.mkdir(parents=True,exist_ok=True)
for name in ['oiram','enemies','events','powerups','simple_mover','tile_handlers','lower']:
    text=(ROOT/f'src/{name}.c').read_text()
    # Unspecified object fields must not inherit allocator garbage on ARM64.
    text=re.sub(r'malloc\(sizeof\((\w+)\)\)',r'oiram_native_calloc(1, sizeof(\1))',text)
    # All original list-removal loops use the old count as the final source index.
    text=re.sub(r'(\w+) = (num_\w+)--;',r'\2--; \1 = \2;',text)
    if name=='tile_handlers':
        old='((unsigned int)(x) - (unsigned int)(tilemap.map))'
        assert old in text
        text=text.replace(old,'((size_t)((x) - tilemap.map))')
    if name=='enemies':
        old='''tile_pntr = (this+tmp1+off);
                        tile = *tile_pntr;'''
        new='''int neighbor = (int)j + tmp1 + off;
                        if (neighbor < 0 || (unsigned)neighbor >= loop) continue;
                        tile_pntr = tilemap.map + neighbor;
                        tile = *tile_pntr;'''
        assert old in text
        text=text.replace(old,new)
    if name=='events':
        old='''remove_simple_mover(i);
                        i = -1;
                        break;'''
        assert old in text
        text=text.replace(old,'''remove_simple_mover(i);
                        i = -1;
                        continue; /* removed cur must not reach HANDLE_SKIP_DRAW */''')
    if name=='events':
        old='''remove_chomper(j);
                                        add_score(cur->score_counter, x, y);'''
        assert old in text
        text=text.replace(old,'''int poof_x = hit->x + 4;
                                        remove_chomper(j);
                                        add_score(cur->score_counter, x, y);''')
        text=text.replace('add_poof(hit->x + 4, y);','add_poof(poof_x, y);',1)
    if name=='events':
        text='#include "presentation.h"\n'+text
        text=re.sub(r'(\w+_t \*cur = [^;]+;)',r'\1\n            native_presentation_entity(cur,0);',text)
        text=text.replace('    // draw the oiram sprite','    native_presentation_entity(&oiram,3);\n    // draw the oiram sprite')
        text=text.replace('        gfx_TransparentSprite(oiram_fail,','        native_presentation_entity(&oiram,0);\n        gfx_TransparentSprite(oiram_fail,')
        text=text.replace('        gfx_TransparentSprite(oiram.sprite,','        native_presentation_entity(&oiram,0);\n        gfx_TransparentSprite(oiram.sprite,')
        text=text.replace('    if (oiram.has_shell) {','    if (oiram.has_shell) {\n        native_presentation_entity(&oiram,1);')
        text=text.replace('    if ((oiram.flags & FLAG_OIRAM_RACOON) && !oiram.on_vine) {','    if ((oiram.flags & FLAG_OIRAM_RACOON) && !oiram.on_vine) {\n        native_presentation_entity(&oiram,2);')
    # Callback-triggered pool evictions retire storage until the current tick ends.
    text=re.sub(r'\bfree\(', 'oiram_native_retire(',text)
    (OUT/f'{name}.c').write_text('/* Generated by scripts/prepare-native.py; source remains src/ */\n'+text)
